class TestResidency(unittest.TestCase):
    def test_it_lives_outside_the_native_core(self):
        self.assertNotIn("native_core", REGION.parts)
        self.assertEqual(REPO, REGION.parent)

    def test_it_depends_only_on_the_agent_contract(self):
        """C1 in spirit: one cross-boundary dependency, and it is the contract."""
        # `native_core.core.trace` and the sibling `observation` module joined
        # under `ACT-CC-R2A-IMPL-001 §31`: this consumer authors the Trace for
        # its own action. The cross-boundary count is still one contract plus
        # the Trace substrate it writes to — no Execution, no Runtime.
        self.assertEqual(
            {"__future__", "typing", "native_core.core.agent",
             "native_core.core.trace", "observation"},
            _module_imports(REGION / "reference_agent.py"),
        )

    def test_it_imports_no_execution_type(self):
        """C2 — the Execution layer is received, never imported.

        Checked by AST over imported *names*, not by substring: the module's
        docstring names these types precisely to explain that it does not import
        them, and a substring search reports that explanation as a violation."""
        imported_names = set()
        for node in ast.walk(ast.parse((REGION / "reference_agent.py").read_text())):
            if isinstance(node, ast.ImportFrom):
                imported_names |= {alias.name for alias in node.names}
            elif isinstance(node, ast.Import):
                imported_names |= {alias.name for alias in node.names}
        self.assertEqual(
            set(),
            imported_names
            & {"Execution", "ExecutionSession", "ExecutionContext", "create_execution_layer"},
        )
        self.assertEqual(
            {"Agent", "annotations", "List", "Tuple",
             "TraceWriter", "TracedAction", "runtime_identity"},
            imported_names,
        )

    def test_it_names_no_runtime_identifier(self):
        """C3 — honoured voluntarily; the region is not bound by it."""
        tree = ast.parse((REGION / "reference_agent.py").read_text())
        names = {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)}
        names |= {n.attr for n in ast.walk(tree) if isinstance(n, ast.Attribute)}
        self.assertEqual(
            set(), names & {"Runtime", "AIOSRuntime", "runtime", "runtime_id"}
        )

    def test_the_region_depends_on_nothing_in_tools(self):
        for path in sorted(REGION.rglob("*.py")):
            for module in _module_imports(path):
                self.assertFalse(module.startswith("tools"), str(path))


