"""
Evidence for E-01 — the first concrete execution consumer.

Scope A — E-01 is a concrete realization of the `Agent` contract.
Scope B — it participates against a real, running Runtime.
Scope C — completion semantics (`spec` §13.3).
Scope D — residency: the region's boundary and dependency direction.
Scope E — the core is unaware of it; no reverse edge, no cycle.
"""

import ast
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from consumers import ReferenceAgent
from native_core.core.agent import Agent
from native_core.core.infrastructure import LocalAppendOnlyStorage, LocalExecutionSubstrate
from native_core.core.runtime import RuntimeState
from native_core.core.runtime.composition import create_runtime
from native_core.core.runtime.execution import create_execution_layer

REGION = Path(__file__).resolve().parent.parent
REPO = REGION.parent


def _running_runtime():
    storage = LocalAppendOnlyStorage(Path(tempfile.mkdtemp()))
    storage.provision()
    substrate = LocalExecutionSubstrate()
    substrate.provision()
    runtime = create_runtime(
        runtime_id="evidence-runtime", storage=storage, substrate=substrate
    )
    runtime.initialize()
    runtime.start()
    return runtime


def _module_imports(path):
    imported = set()
    for node in ast.walk(ast.parse(path.read_text())):
        if isinstance(node, ast.ImportFrom):
            imported.add(node.module or "")
        elif isinstance(node, ast.Import):
            imported |= {alias.name for alias in node.names}
    return imported


