class TestTheCoreRemainsUnaware(unittest.TestCase):
    def test_the_native_core_imports_nothing_from_consumers(self):
        """The reverse edge the region exists to prevent."""
        core = REPO / "native_core"
        for path in sorted(core.rglob("*.py")):
            for module in _module_imports(path):
                self.assertFalse(
                    module.startswith("consumers"), f"{path} imports consumers"
                )

    def test_tools_imports_nothing_from_consumers(self):
        for path in sorted((REPO / "tools").rglob("*.py")):
            for module in _module_imports(path):
                self.assertFalse(module.startswith("consumers"), str(path))

    def test_importing_the_core_does_not_load_the_region(self):
        program = (
            "import sys;"
            "import native_core.core.agent, native_core.core.runtime;"
            "print('CONSUMERS=' + repr([m for m in sys.modules if m.startswith('consumers')]))"
        )
        result = subprocess.run(
            [sys.executable, "-c", program], capture_output=True, text=True, cwd=str(REPO)
        )
        self.assertEqual(0, result.returncode, result.stderr)
        self.assertIn("CONSUMERS=[]", result.stdout)


